    @classmethod
    async def invoke_stream(cls, payload: dict) -> AsyncGenerator[str, None]:
        """Streaming request to the selected Bedrock Responses endpoint.

        The Responses API streams *named* SSE events. We translate:
          response.output_text.delta            → content delta
          response.function_call_arguments.delta → tool_call argument delta
          response.output_item.added (func call) → tool_call opener (id + name)
          response.completed                     → usage + final stop
        into OpenAI chat.completion.chunk SSE lines.
        """
        model = payload.get("model", "")
        target = cls._endpoint(model, payload.get("service_tier"))
        body = _openai_to_responses(payload)
        body["stream"] = True
        _log_request_structure(body, target)
        body_bytes = json.dumps(body).encode("utf-8")
        headers = await signed_headers(
            "POST",
            target.url,
            body_bytes,
            target.region,
            service=target.sigv4_service,
        )
        headers["Accept"] = "text/event-stream"

        chunk_id = f"chatcmpl-{uuid.uuid4().hex}"
        created = time.time_ns() // 1_000_000_000
        # Map Responses output_index → OpenAI tool_call index (function calls only)
        tool_call_index: Dict[int, int] = {}

        def _chunk(
            delta: Dict[str, Any],
            finish: Optional[str],
            usage=None,
            service_tier: Optional[str] = None,
        ) -> str:
            obj: Dict[str, Any] = {
                "id": chunk_id,
                "object": "chat.completion.chunk",
                "created": created,
                "model": model,
                "choices": [{"index": 0, "delta": delta, "finish_reason": finish}],
            }
            if usage is not None:
                obj["usage"] = usage
            if service_tier:
                obj["service_tier"] = service_tier
            return f"data: {json.dumps(obj)}\n\n"

        async with httpx.AsyncClient(timeout=3600) as client:
            async with client.stream(
                "POST", target.url, headers=headers, content=body_bytes
            ) as resp:
                if resp.status_code != 200:
                    await resp.aread()
                    raise httpx.HTTPStatusError(
                        f"OpenAI Responses stream returned {resp.status_code}",
                        request=resp.request,
                        response=resp,
                    )

                event_name: Optional[str] = None
                async for line in resp.aiter_lines():
                    if not line:
                        event_name = None
                        continue
                    if line.startswith("event:"):
                        event_name = line[6:].strip()
                        continue
                    if not line.startswith("data:"):
                        continue
                    data_str = line[5:].strip()
                    if not data_str or data_str == "[DONE]":
                        continue
                    try:
                        event = json.loads(data_str)
                    except json.JSONDecodeError:
                        continue

                    etype = event.get("type") or event_name

                    if etype == "response.output_text.delta":
                        delta_text = event.get("delta", "")
                        if delta_text:
                            yield _chunk({"content": delta_text}, None)

                    elif etype == "response.output_item.added":
                        item = event.get("item") or {}
                        if item.get("type") == "function_call":
                            oidx = event.get("output_index", 0)
                            tc_idx = len(tool_call_index)
                            tool_call_index[oidx] = tc_idx
                            yield _chunk(
                                {
                                    "tool_calls": [
                                        {
                                            "index": tc_idx,
                                            "id": item.get("call_id")
                                            or f"call_{uuid.uuid4().hex[:16]}",
                                            "type": "function",
                                            "function": {
                                                "name": item.get("name", ""),
                                                "arguments": "",
                                            },
                                        }
                                    ]
                                },
                                None,
                            )

                    elif etype == "response.function_call_arguments.delta":
                        oidx = event.get("output_index", 0)
                        tc_idx = tool_call_index.get(oidx, 0)
                        yield _chunk(
                            {
                                "tool_calls": [
                                    {
                                        "index": tc_idx,
                                        "function": {
                                            "arguments": event.get("delta", "")
                                        },
                                    }
                                ]
                            },
                            None,
                        )

                    elif etype in ("response.completed", "response.incomplete"):
                        resp_obj = event.get("response") or {}
                        usage = _build_usage(resp_obj.get("usage") or {})
                        finish = (
                            "tool_calls"
                            if tool_call_index
                            else (
                                "length" if etype == "response.incomplete" else "stop"
                            )
                        )
                        yield _chunk(
                            {},
                            finish,
                            usage=usage,
                            service_tier=resp_obj.get("service_tier"),
                        )

                    elif etype == "response.failed" or etype == "error":
                        resp_obj = event.get("response") or {}
                        error = resp_obj.get("error") or event.get("error") or {}
                        logger.error(
                            "Responses stream failed: backend=%s, model=%s, "
                            "error_type=%s, error_code=%s",
                            target.backend,
                            model,
                            error.get("type", "unknown"),
                            error.get("code", "unknown"),
                        )
                        public_error = {
                            "error": {
                                "message": "Bedrock Responses stream failed",
                                "type": error.get("type", "server_error"),
                                "code": error.get("code", "upstream_failed"),
                            }
                        }
                        yield f"data: {json.dumps(public_error)}\n\n"
                        return

        yield "data: [DONE]\n\n"
