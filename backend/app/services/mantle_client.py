class ResponsesRequestValidationError(ValueError):
    """A request option the exact target model cannot honour (HTTP 400).

    Messages are generated by the gateway (no request content), so endpoints
    may return them to the client verbatim.
    """


class PromptCacheValidationError(ResponsesRequestValidationError):
    """An explicit cache marker the exact target cannot honour."""


class ServiceTierValidationError(ResponsesRequestValidationError):
    """A ``service_tier`` the exact target does not offer."""


def validate_service_tier(model: str, service_tier: Any) -> None:
    """Reject Ultrafast for routes whose model card does not offer it."""
    if not is_ultrafast(service_tier):
        return
    route = resolve_gpt_route(model)
    if route is None or route.ultrafast_pricing is None:
        raise ServiceTierValidationError(
            f"{model} does not support service_tier 'ultrafast'"
        )


# Chat Completions content-part type → Responses input content type.
_CHAT_PART_TO_RESPONSES_TYPE = {
    "text": "input_text",
    "image_url": "input_image",
}


def _check_breakpoint_capability(model: str, content_type: str) -> None:
    """Raise unless *model* accepts an explicit breakpoint on *content_type*."""
    route = resolve_gpt_route(model)
    allowed = route.prompt_cache.explicit_content_types if route else frozenset()
    if not allowed:
        raise PromptCacheValidationError(
            f"{model} does not support explicit prompt caching"
        )
    if content_type not in allowed:
        raise PromptCacheValidationError(
            f"{model} does not support explicit prompt cache breakpoints on "
            f"{content_type} content; supported: {', '.join(sorted(allowed))}"
        )


def validate_responses_cache_markers(payload: Dict[str, Any]) -> None:
    """Reject markers the exact target model cannot honour.

    Checks the breakpoint count, assistant/tool placement, and — per the GPT
    catalog — whether the model supports explicit caching on that content
    type. Raising here (before any upstream call or stream) gives the client a
    clear 4xx instead of a silently dropped marker.
    """
    model = payload.get("model", "")
    validate_service_tier(model, payload.get("service_tier"))
    breakpoint_count = 0
    for message in payload.get("messages") or []:
        if not isinstance(message, dict):
            continue
        content = message.get("content")
        if not isinstance(content, list):
            continue
        marked_parts = [
            part
            for part in content
            if isinstance(part, dict) and part.get("cache_control")
        ]
        breakpoint_count += len(marked_parts)
        if marked_parts and message.get("role") == "assistant":
            raise PromptCacheValidationError(
                "Explicit prompt cache breakpoints are not supported "
                "on assistant content for Responses API models"
            )
        if marked_parts and message.get("role") == "tool":
            raise PromptCacheValidationError(
                "Explicit prompt cache breakpoints are not supported inside "
                "tool results; place the breakpoint on a preceding text block"
            )
        for part in marked_parts:
            content_type = _CHAT_PART_TO_RESPONSES_TYPE.get(part.get("type"))
            if content_type is None:
                raise PromptCacheValidationError(
                    "Explicit prompt cache breakpoints are not supported on "
                    f"{part.get('type', 'unknown')} content parts"
                )
            _check_breakpoint_capability(model, content_type)

    for tool in payload.get("tools") or []:
        if isinstance(tool, dict) and tool.get("cache_control"):
            raise PromptCacheValidationError(
                "Explicit prompt cache breakpoints are not supported directly on tool "
                "definitions; place the breakpoint on a following text or image block"
            )

    if breakpoint_count > 4:
        raise PromptCacheValidationError(
            "At most 4 prompt cache breakpoints are allowed"
        )


def validate_native_responses_cache(body: Dict[str, Any]) -> None:
    """Validate explicit cache usage in a native Responses request body.

    Scans message ``content`` and ``function_call_output.output`` lists; any
    part carrying a ``prompt_cache_breakpoint`` key (even empty) is counted
    and checked against the exact model's capability.
    """
    model = body.get("model", "")
    validate_service_tier(model, body.get("service_tier"))
    options = body.get("prompt_cache_options")
    if isinstance(options, dict) and options.get("mode") == "explicit":
        route = resolve_gpt_route(model)
        if route is None or not route.prompt_cache.explicit:
            raise PromptCacheValidationError(
                f"{model} does not support explicit prompt caching"
            )

    breakpoint_count = 0
    items = body.get("input")
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict):
            continue
        for key in ("content", "output"):
            parts = item.get(key)
            for part in parts if isinstance(parts, list) else []:
                if isinstance(part, dict) and "prompt_cache_breakpoint" in part:
                    breakpoint_count += 1
                    _check_breakpoint_capability(
                        model, str(part.get("type", "unknown"))
                    )
    if breakpoint_count > 4:
        raise PromptCacheValidationError(
            "At most 4 prompt cache breakpoints are allowed"
        )


def _content_part_to_responses(part: Dict[str, Any]) -> Dict[str, Any]:
    """Convert one OpenAI ContentPart dict to a Responses API input part."""
    ptype = part.get("type")
    converted: Dict[str, Any]
    if ptype == "text":
        converted = {"type": "input_text", "text": part.get("text", "")}
    elif ptype == "image_url":
        url = (part.get("image_url") or {}).get("url", "")
        # Responses API takes the data-URL / URL directly on input_image.
        converted = {"type": "input_image", "image_url": url}
    else:
        # Unknown type — best-effort text fallback
        converted = {"type": "input_text", "text": str(part.get("text", ""))}

    cache_control = part.get("cache_control")
    if isinstance(cache_control, dict) and cache_control.get("type") == "ephemeral":
        converted["prompt_cache_breakpoint"] = {"mode": "explicit"}
    return converted


def _msg_content_to_input_parts(content: Any, output: bool) -> List[Dict[str, Any]]:
    """Convert an OpenAI message content value (str or list) to Responses parts.

    *output* selects the text part type: assistant turns use ``output_text``,
    everything else uses ``input_text``.
    """
    text_type = "output_text" if output else "input_text"
    if content is None:
        return []
    if isinstance(content, str):
        return [{"type": text_type, "text": content}] if content else []
    if isinstance(content, list):
        parts = []
        for p in content:
            if isinstance(p, dict):
                # Assistant text parts must use output_text in the Responses API,
                # which does not support explicit prompt-cache breakpoints.
                if output and p.get("type") == "text":
                    if p.get("cache_control"):
                        raise PromptCacheValidationError(
                            "Explicit prompt cache breakpoints are not supported "
                            "on assistant content for Responses API models"
                        )
                    parts.append({"type": "output_text", "text": p.get("text", "")})
                else:
                    parts.append(_content_part_to_responses(p))
        return parts
    return [{"type": text_type, "text": str(content)}]


def _openai_messages_to_input(
    messages: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Convert an OpenAI messages array to a Responses API ``input`` list.

    Roles:
      system     → message with role "developer"
      user       → message with role "user"
      assistant  → message with role "assistant" (tool_calls → function_call items)
      tool       → function_call_output item (keyed by call_id)
    """
    input_items: List[Dict[str, Any]] = []

    for msg in messages:
        role = msg.get("role", "user")
        content = msg.get("content")
        tool_calls = msg.get("tool_calls")

        # ── tool result ─────────────────────────────────────────────────────
        if role == "tool":
            raw = content or ""
            output = (
                _msg_content_to_input_parts(raw, output=False)
                if isinstance(raw, list)
                else (raw if isinstance(raw, str) else json.dumps(raw))
            )
            input_items.append(
                {
                    "type": "function_call_output",
                    "call_id": msg.get("tool_call_id", ""),
                    "output": output,
                }
            )
            continue

        # ── system → developer ──────────────────────────────────────────────
        if role == "system":
            parts = _msg_content_to_input_parts(content, output=False)
            if parts:
                input_items.append({"role": "developer", "content": parts})
            continue

        # ── user / assistant ─────────────────────────────────────────────────
        is_assistant = role == "assistant"
        parts = _msg_content_to_input_parts(content, output=is_assistant)
        if parts:
            input_items.append(
                {"role": "assistant" if is_assistant else "user", "content": parts}
            )

        # Assistant tool calls → function_call items
        for tc in tool_calls or []:
            fn = tc.get("function") or {}
            input_items.append(
                {
                    "type": "function_call",
                    "call_id": tc.get("id", ""),
                    "name": fn.get("name", ""),
                    "arguments": fn.get("arguments", "{}"),
                }
            )

    return input_items


def _has_explicit_prompt_cache_breakpoint(input_items: List[Dict[str, Any]]) -> bool:
    """Return whether converted Responses input contains a client breakpoint."""
    for item in input_items:
        content = item.get("content")
        if not isinstance(content, list):
            continue
        for part in content:
            if isinstance(part, dict) and "prompt_cache_breakpoint" in part:
                return True
    return False


def _openai_tools_to_responses(
    tools: Optional[List[Dict[str, Any]]],
) -> Optional[List[Dict[str, Any]]]:
    """Convert OpenAI ChatCompletions tools to Responses API tools.

    Responses flattens the function spec (name/description/parameters live at the
    top level of the tool, not nested under a ``function`` key).
    """
    if not tools:
        return None
    out = []
    for tool in tools:
        if tool.get("type") == "function":
            fn = tool.get("function") or {}
            decl: Dict[str, Any] = {"type": "function", "name": fn.get("name", "")}
            if fn.get("description"):
                decl["description"] = fn["description"]
            if fn.get("parameters"):
                decl["parameters"] = fn["parameters"]
            if fn.get("strict") is not None:
                decl["strict"] = fn["strict"]
            out.append(decl)
    return out or None


def _openai_response_format_to_text_format(
    response_format: Any,
) -> Optional[Dict[str, Any]]:
    """Convert OpenAI ``response_format`` to a Responses API ``text.format`` value.

    OpenAI ChatCompletions nests the JSON schema under ``json_schema`` with the
    spec inside; the Responses API flattens ``name``/``schema``/``strict`` to the
    top level of ``text.format``.

      {"type": "text"}                       → {"type": "text"}
      {"type": "json_object"}                → {"type": "json_object"}
      {"type": "json_schema",
       "json_schema": {"name", "schema", "strict"}}
                                             → {"type": "json_schema",
                                                "name", "schema", "strict"}
    """
    if not isinstance(response_format, dict):
        return None
    rf_type = response_format.get("type")
    if rf_type in ("text", "json_object"):
        return {"type": rf_type}
    if rf_type == "json_schema":
        js = response_format.get("json_schema") or {}
        fmt: Dict[str, Any] = {"type": "json_schema"}
        if js.get("name"):
            fmt["name"] = js["name"]
        if js.get("schema") is not None:
            fmt["schema"] = js["schema"]
        if js.get("description"):
            fmt["description"] = js["description"]
        if js.get("strict") is not None:
            fmt["strict"] = js["strict"]
        return fmt
    return None


def _openai_tool_choice_to_responses(tool_choice: Any) -> Optional[Any]:
    """Convert OpenAI tool_choice to a Responses API tool_choice value."""
    if tool_choice is None:
        return None
    if tool_choice in ("none", "auto", "required"):
        return tool_choice
    if isinstance(tool_choice, dict) and tool_choice.get("type") == "function":
        fn_name = (tool_choice.get("function") or {}).get("name")
        if fn_name:
            return {"type": "function", "name": fn_name}
    return None


# Model families whose mantle-served members are reasoning models (reject
# temperature/top_p).  Family prefixes rather than exact versions so
# auto-discovered future releases are classified without a code change.
# No trailing separator: members may be versioned with a dot (gpt-5.6-luna,
# gpt-5.7) OR a bare codename with a dash (gpt-6-astra), and both must match.
_REASONING_MODEL_PATTERNS = ("gpt-5", "gpt-6", "o1", "o3", "o4")


def _is_reasoning_model(model: str) -> bool:
    return any(pat in model for pat in _REASONING_MODEL_PATTERNS)


def _openai_to_responses(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Convert a full OpenAI chat completion payload to a Responses request body.

    Mappings:
      model               → model
      messages            → input  (system → developer role)
      max_tokens          → max_output_tokens
      temperature         → temperature
      top_p               → top_p
      tools               → tools  (flattened function spec)
      tool_choice         → tool_choice
      reasoning.effort    ← bedrock_additional_model_request_fields.reasoning.effort
                            (no new schema field; reuse the existing passthrough)

    OpenAI-only fields (frequency_penalty, n, presence_penalty, etc.) are
    silently ignored.
    """
    validate_responses_cache_markers(payload)
    messages = payload.get("messages") or []
    input_items = _openai_messages_to_input(messages)
    body: Dict[str, Any] = {
        "model": payload.get("model", ""),
        "input": input_items,
    }
    if _has_explicit_prompt_cache_breakpoint(input_items):
        # Explicit mode disables the automatic latest-message breakpoint, so
        # only prefixes selected by the client incur cache-write charges.
        body["prompt_cache_options"] = {"mode": "explicit"}

    if payload.get("service_tier") is not None:
        body["service_tier"] = payload["service_tier"]

    if payload.get("max_tokens") is not None:
        body["max_output_tokens"] = payload["max_tokens"]
    is_reasoning = _is_reasoning_model(body["model"])
    if not is_reasoning and payload.get("temperature") is not None:
        body["temperature"] = payload["temperature"]
    if not is_reasoning and payload.get("top_p") is not None:
        body["top_p"] = payload["top_p"]

    tools = _openai_tools_to_responses(payload.get("tools"))
    if tools:
        body["tools"] = tools
    tool_choice = _openai_tool_choice_to_responses(payload.get("tool_choice"))
    if tool_choice is not None:
        body["tool_choice"] = tool_choice

    # response_format → text.format (structured / JSON output)
    text_format = _openai_response_format_to_text_format(payload.get("response_format"))
    if text_format is not None:
        body["text"] = {"format": text_format}

    # reasoning_effort: standard OpenAI field, or via bedrock_additional_model_request_fields
    effort = payload.get("reasoning_effort")
    if not effort:
        extra = payload.get("bedrock_additional_model_request_fields") or {}
        reasoning = extra.get("reasoning")
        if isinstance(reasoning, dict):
            effort = reasoning.get("effort")
    if effort:
        body["reasoning"] = {"effort": effort}

    return body


